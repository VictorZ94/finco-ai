from rest_framework import serializers

from .models import Conversation, Message


class ConversationSerializer(serializers.ModelSerializer):
    class Meta:
        model = Conversation
        fields = ["id", "title", "created_at", "updated_at"]
        read_only_fields = fields


class MessageSerializer(serializers.ModelSerializer):
    class Meta:
        model = Message
        fields = ["id", "role", "content", "data", "created_at"]
        read_only_fields = fields


class SendMessageSerializer(serializers.Serializer):
    content = serializers.CharField(max_length=2000, trim_whitespace=True)
    # The user's local date (the server runs in UTC); used for "today" and the default applied date.
    today = serializers.DateField(required=False)
    # Generated by the frontend per message, so a retried request isn't run twice.
    client_id = serializers.UUIDField(required=False)


class ProposalAnswerSerializer(serializers.Serializer):
    accept = serializers.BooleanField()
    today = serializers.DateField(required=False)
